#[derive(Default)]
struct FoundOffsets {
    master: Option<PointerPath>,
    bpm: [Option<PointerPath>; 4],
    pos: [Option<PointerPath>; 4],
    track: [Option<PointerPath>; 4],
    anlz: [Option<PointerPath>; 4],
}

impl FoundOffsets {
    fn to_block(&self, version: &str) -> String {
        let mut s = format!("{version}\n# Master deck index\n{}\n", line_or_todo(&self.master));
        for d in 0..4 {
            s.push_str(&format!("\n# Deck {}\n", d + 1));
            s.push_str(&line_or_todo(&self.bpm[d]));
            s.push('\n');
            s.push_str(&line_or_todo(&self.pos[d]));
            s.push('\n');
            s.push_str(&line_or_todo(&self.track[d]));
            s.push('\n');
            s.push_str(&line_or_todo(&self.anlz[d]));
            s.push('\n');
        }
        s
    }
}

fn line_or_todo(p: &Option<PointerPath>) -> String {
    p.as_ref().map(|p| p.to_line()).unwrap_or_else(|| "# TODO not found".to_string())
}

fn report(label: &str, p: &Option<PointerPath>) {
    match p {
        Some(p) => println!("  ✓ {label}: {}", p.to_line()),
        None => println!("  ⚠ {label}: not found"),
    }
}

