/// Parse an offset-file line ("RVA o1 .. final", all hex) into a PointerPath.
fn parse_pointer_line(line: &str) -> Option<PointerPath> {
    let nums: Vec<usize> = line
        .split_whitespace()
        .map(|t| usize::from_str_radix(t, 16).ok())
        .collect::<Option<Vec<_>>>()?;
    (nums.len() >= 2).then(|| PointerPath { rva: nums[0], rest: nums[1..].to_vec() })
}

fn cmd_check(mem: &ProcMem, args: &[String]) {
    let Some(kind) = args.get(2) else {
        eprintln!("usage: check <f32|i64|u8|str> <RVA o1 ... final>");
        return;
    };
    let nums: Option<Vec<usize>> = args[3..]
        .iter()
        .map(|t| usize::from_str_radix(t, 16).ok())
        .collect();
    let Some(nums) = nums.filter(|n| n.len() >= 2) else {
        eprintln!("bad chain");
        return;
    };
    let path = PointerPath { rva: nums[0], rest: nums[1..].to_vec() };
    let Some(addr) = path.resolve_addr(mem) else {
        println!("{}  ->  (unresolved)", path.to_line());
        return;
    };
    let v = match kind.as_str() {
        "f32" => mem.read::<f32>(addr).map(|v| format!("{v}")),
        "i64" => mem.read::<i64>(addr).map(|v| format!("{v}")),
        "u8" => mem.read::<u8>(addr).map(|v| format!("{v}")),
        "str" => mem.read_cstring(addr, 300),
        _ => Some("(unknown type)".into()),
    };
    println!("{}  ->  0x{addr:X}  =  {}", path.to_line(), v.unwrap_or_else(|| "(read failed)".into()));
}

