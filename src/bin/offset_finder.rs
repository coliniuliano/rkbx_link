/// The `n` most-recently-modified .DAT files, returned in DECK ORDER (assuming
/// decks were analysed 1→n): index 0 = oldest of the n = deck 1.
fn newest_dats_in_deck_order(n: usize) -> Vec<String> {
    let mut all: Vec<(std::time::SystemTime, String)> = Vec::new();
    if let Ok(home) = std::env::var("HOME") {
        for root in [
            format!("{home}/Library/Pioneer/rekordbox"),
            format!("{home}/Library/Application Support/Pioneer/rekordbox/share"),
        ] {
            collect_dats(std::path::Path::new(&root), &mut all);
        }
    }
    all.sort_by(|a, b| b.0.cmp(&a.0)); // newest first
    all.truncate(n);
    all.sort_by(|a, b| a.0.cmp(&b.0)); // oldest→newest == deck 1→n
    all.into_iter().map(|(_, p)| p).collect()
}

fn collect_dats(dir: &std::path::Path, out: &mut Vec<(std::time::SystemTime, String)>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for e in entries.flatten() {
        let path = e.path();
        if path.is_dir() {
            collect_dats(&path, out);
        } else if path.extension().and_then(|x| x.to_str()) == Some("DAT") {
            if let Ok(modt) = std::fs::metadata(&path).and_then(|m| m.modified()) {
                out.push((modt, path.to_string_lossy().to_string()));
            }
        }
    }
}

fn detect_version() -> Option<String> {
    let out = std::process::Command::new("defaults")
        .args([
            "read",
            "/Applications/rekordbox 7/rekordbox.app/Contents/Info.plist",
            "CFBundleShortVersionString",
        ])
        .output()
        .ok()?;
    let s = String::from_utf8_lossy(&out.stdout).trim().to_string();
    (!s.is_empty()).then(|| s.split('.').take(3).collect::<Vec<_>>().join("."))
}

fn append_block(path: &str, block: &str) -> Result<(), String> {
    let mut existing = std::fs::read_to_string(path).unwrap_or_default();
    if !existing.ends_with('\n') {
        existing.push('\n');
    }
    existing.push('\n');
    existing.push('\n');
    existing.push_str(block);
    std::fs::write(path, existing).map_err(|e| e.to_string())
}

