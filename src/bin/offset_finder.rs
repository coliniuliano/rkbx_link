/// The shortest reverse-scan chain reaching `addr` (chains come shortest-first).
fn shortest_chain(scanner: &Scanner, addr: usize, max_depth: usize) -> Option<PointerPath> {
    let opts = ScanOpts { max_depth, ..ScanOpts::default() };
    scanner.reverse_scan(addr, opts).into_iter().next()
}

/// Offset from `addr` to the nearby i64 closest to `target` within `tol`
/// (used to spot THIS deck's playhead beside its BPM). Searches a small window.
fn find_i64_offset_near(mem: &ProcMem, addr: usize, target: i64, tol: i64) -> Option<i64> {
    let base = addr as i64;
    let mut best: Option<(i64, i64)> = None; // (err, delta)
    let mut d = -0x600i64;
    while d <= 0x600 {
        if let Some(v) = mem.read::<i64>((base + d) as usize) {
            let err = (v - target).abs();
            if err <= tol && best.map(|(e, _)| err < e).unwrap_or(true) {
                best = Some((err, d));
            }
        }
        d += 8;
    }
    best.map(|(_, d)| d)
}

/// Discover sample_position + current_bpm for ALL FOUR decks as the CANONICAL
/// deck array — the only form that survives Rekordbox restarts / track changes.
///
/// A single-launch reverse-scan finds many chains that read the right value NOW
/// but route through transient/aliased pointers that reconstruct differently on
/// restart. The launch-stable route is the real deck array: a static base whose
/// deck-index offset (rest[0]) steps through CONSECUTIVE stride-8 pointer-array
/// slots, each reaching a deck struct via the SAME subchain. We therefore accept
/// a seed only if shifting rest[0] by 8 lands on 4 slots reading the 4 distinct
/// BPMs — that structural constraint is what pins the exact canonical offsets.
fn discover_decks_pos_bpm(
    scanner: &Scanner,
    mem: &ProcMem,
    expected: [i64; 4],
    bpms: [f32; 4],
) -> ([Option<PointerPath>; 4], [Option<PointerPath>; 4]) {
    // There can be several canonical-looking deck arrays (e.g. a display copy
    // alongside the real one). The one rkbx_link uses is the SHORTEST chain, so
    // collect all canonical candidates and keep the shallowest (then smallest
    // offsets). Depth 3 is optimal (base→array→struct→value), so stop early once
    // found.
    let opts = ScanOpts { max_depth: 6, max_results: 8000, ..ScanOpts::default() };
    let mut best: Option<(usize, usize, ([Option<PointerPath>; 4], [Option<PointerPath>; 4]))> = None;
    for sd in 0..4 {
        for &ba in scanner.find_f32(bpms[sd], 0.05).iter() {
            // Require a seeked playhead beside this BPM so we anchor on a real
            // deck object, not a constant/collection copy.
            if find_i64_offset_near(mem, ba, expected[sd], 3 * SAMPLE_RATE).is_none() {
                continue;
            }
            for seed in scanner.reverse_scan(ba, opts) {
                let Some(res) = canon_from_seed(mem, &seed, &bpms, &expected) else {
                    continue;
                };
                let bpm0 = res.1[0].as_ref().unwrap();
                let depth = bpm0.depth();
                let offsum: usize = bpm0.rest.iter().sum();
                if best.as_ref().map(|(d, s, _)| (depth, offsum) < (*d, *s)).unwrap_or(true) {
                    best = Some((depth, offsum, res));
                }
                if depth <= 3 {
                    return best.unwrap().2; // optimal — can't do better
                }
            }
        }
    }
    best.map(|(_, _, r)| r).unwrap_or(([None, None, None, None], [None, None, None, None]))
}

/// If `seed` (which reads some deck's BPM) is one slot of the canonical deck
/// array, return per-deck bpm+pos chains sharing that base. Requires: shifting
/// rest[0] by stride-8 across 4 CONSECUTIVE slots yields the 4 distinct BPMs
/// (the array signature). pos is the sibling i64 in the same value struct whose
/// value matches each deck's seeked position (found once, shared by all decks).
fn canon_from_seed(
    mem: &ProcMem,
    seed: &PointerPath,
    bpms: &[f32; 4],
    expected: &[i64; 4],
) -> Option<([Option<PointerPath>; 4], [Option<PointerPath>; 4])> {
    let idx0 = seed.rest[0];
    let bpm_final = *seed.rest.last().unwrap() as i64;
    for k0 in 0..4usize {
        let Some(base_idx) = idx0.checked_sub(8 * k0) else { continue };
        // Resolve the 4 consecutive slots; each must read a distinct known BPM.
        let mut bpm_addr = [0usize; 4];
        let mut assign = [usize::MAX; 4]; // slot k → deck index j
        let mut ok = true;
        for k in 0..4 {
            let mut rest = seed.rest.clone();
            rest[0] = base_idx + 8 * k;
            let Some(a) = (PointerPath { rva: seed.rva, rest }).resolve_addr(mem) else {
                ok = false;
                break;
            };
            let Some(v) = mem.read::<f32>(a).filter(|v| v.is_finite()) else {
                ok = false;
                break;
            };
            let Some(j) = (0..4).find(|&j| (v - bpms[j]).abs() <= 1.5) else {
                ok = false;
                break;
            };
            assign[k] = j;
            bpm_addr[k] = a;
        }
        if !ok {
            continue;
        }
        // All 4 decks must be represented exactly once.
        let mut seen = [false; 4];
        if assign.iter().any(|&j| j == usize::MAX || std::mem::replace(&mut seen[j], true)) {
            continue;
        }

        // pos: an i64 offset (within the value struct) whose value matches each
        // deck's seeked position — same offset for all decks.
        let mut pos_final = None;
        'find: for off in (0..0x400).step_by(4) {
            for k in 0..4 {
                let vs = bpm_addr[k] as i64 - bpm_final; // value struct base
                match mem.read::<i64>((vs + off) as usize) {
                    Some(v) if (v - expected[assign[k]]).abs() <= 3 * SAMPLE_RATE => {}
                    _ => continue 'find,
                }
            }
            pos_final = Some(off as usize);
            break;
        }

        // Build per-deck chains (indexed by real deck j).
        let mut bpm_out: [Option<PointerPath>; 4] = [None, None, None, None];
        let mut pos_out: [Option<PointerPath>; 4] = [None, None, None, None];
        for k in 0..4 {
            let j = assign[k];
            let mut rest = seed.rest.clone();
            rest[0] = base_idx + 8 * k;
            bpm_out[j] = Some(PointerPath { rva: seed.rva, rest: rest.clone() });
            if let Some(pf) = pos_final {
                *rest.last_mut().unwrap() = pf;
                pos_out[j] = Some(PointerPath { rva: seed.rva, rest });
            }
        }
        return Some((pos_out, bpm_out));
    }
    None
}

/// Pick, for each deck, a candidate chain that shares ONE common base RVA across
/// all four decks (the deck-array signature), preferring the shallowest set. If
/// no base is common to all four, fall back to each deck's shortest candidate.
fn enforce_shared_base(cands: &[Vec<PointerPath>; 4]) -> [Option<PointerPath>; 4] {
    let mut bases: Vec<usize> = cands[0].iter().map(|c| c.rva).collect();
    bases.sort_unstable();
    bases.dedup();
    let mut best: Option<(usize, [Option<PointerPath>; 4])> = None;
    for base in bases {
        let mut picks: [Option<PointerPath>; 4] = [None, None, None, None];
        let mut total = 0usize;
        let mut ok = true;
        for d in 0..4 {
            match cands[d]
                .iter()
                .filter(|c| c.rva == base)
                .min_by_key(|c| (c.depth(), c.rest.iter().sum::<usize>()))
            {
                Some(c) => {
                    total += c.depth();
                    picks[d] = Some(c.clone());
                }
                None => {
                    ok = false;
                    break;
                }
            }
        }
        if ok && best.as_ref().map(|(t, _)| total < *t).unwrap_or(true) {
            best = Some((total, picks));
        }
    }
    best.map(|(_, p)| p)
        .unwrap_or_else(|| std::array::from_fn(|d| cands[d].first().cloned()))
}

/// The deck struct address for a deck, from its (canonical) bpm chain:
/// `read(read(base+rva) + deck_index)`. This is the shared parent of the deck's
/// bpm/pos/track fields — the restart-stable anchor track_info hangs off.
fn deck_struct_addr(mem: &ProcMem, bpm: &PointerPath) -> Option<usize> {
    let array = mem.read_u64(mem.base + bpm.rva)? as usize;
    let deck_index = *bpm.rest.first()?;
    Some(mem.read_u64(array + deck_index)? as usize)
}

/// Find the master-index chain: the byte that tracks the master deck as it is
/// switched 1→2→3→4, located by diffing capped memory snapshots.
fn discover_master(scanner: &Scanner, mem: &ProcMem) -> Option<PointerPath> {
    const CAP: usize = 32 * 1024 * 1024;
    println!("Set the tempo MASTER to DECK 1 (press deck 1's MASTER button).");
    pause("Press Enter with DECK 1 as master");
    let s0 = scanner.snapshot_capped(CAP);
    println!("Now set the tempo MASTER to DECK 2.");
    pause("Press Enter with DECK 2 as master");
    let s1 = scanner.snapshot_capped(CAP);

    let mut addrs = Scanner::diff_byte(&s0, &s1, 0, 1);
    println!("  master: {} bytes went 0→1.", addrs.len());
    for (deck, want) in [(3u8, 2u8), (4, 3)] {
        println!("Set the tempo MASTER to DECK {deck}.");
        pause(&format!("Press Enter with DECK {deck} as master"));
        addrs.retain(|&a| mem.read::<u8>(a) == Some(want));
        println!("  master: {} consistent.", addrs.len());
    }
    // Master is now deck 4 (index 3). Build a chain per surviving byte, and note
    // the address each resolves to now.
    let mut cands: Vec<(PointerPath, usize)> = addrs
        .iter()
        .take(400)
        .filter_map(|a| shortest_chain(scanner, *a, 5).map(|c| (c, *a)))
        .collect();
    println!("  master: {} candidate chains before reload check.", cands.len());
    // Reload a track to reshuffle the heap. A restart-stable chain reconstructs
    // to the SAME address (still reading 3); a chain through a transient/track-
    // tied pointer now resolves elsewhere (or to garbage) — drop it. Requiring
    // the same address (not merely a byte that reads 3) is the strict test.
    println!("Now LOAD A DIFFERENT track on DECK 1 (leave DECK 4 as master).");
    pause("Press Enter once deck 1 has a different track");
    cands.retain(|(c, addr)| c.resolve_addr(mem) == Some(*addr) && mem.read::<u8>(*addr) == Some(3));
    println!("  master: {} chains survived the reload.", cands.len());

    // Save survivors for the optional restart-validation pass (`master-verify`).
    let saved: String = cands.iter().map(|(c, _)| c.to_line()).collect::<Vec<_>>().join("\n");
    let _ = std::fs::write(master_cand_file(), saved);
    if cands.len() > 1 {
        println!(
            "  (Note: {} chains still tie. For a BULLETPROOF pick, restart Rekordbox,\n   set master to any deck, and run: offset_finder master-verify <that-deck-1..4>)",
            cands.len()
        );
    }
    cands
        .into_iter()
        .map(|(c, _)| c)
        .min_by_key(|c| (c.depth(), c.rest.iter().sum::<usize>()))
}

fn master_cand_file() -> std::path::PathBuf {
    std::env::temp_dir().join("rkbx_master_candidates.txt")
}

/// Build a deck's track chain from the shared subchain: `base` + deck-index +
/// subchain. If the subchain doesn't reach this deck's title directly (its
/// per-deck offset differs), substitute the single differing offset by scanning.
fn track_chain_for_deck(
    mem: &ProcMem,
    base_rva: usize,
    deck_index: usize,
    title: &str,
    shared: &[usize],
) -> Option<PointerPath> {
    let build = |sub: &[usize]| {
        let mut rest = vec![deck_index];
        rest.extend_from_slice(sub);
        PointerPath { rva: base_rva, rest }
    };
    let direct = build(shared);
    if reads_title(mem, &direct, title) {
        return Some(direct);
    }
    // One offset differs per deck (e.g. the title-slot index). Find it.
    let mut sub = shared.to_vec();
    for j in 0..sub.len() {
        let orig = sub[j];
        let mut v = 0usize;
        while v <= 0x400 {
            sub[j] = v;
            let c = build(&sub);
            if reads_title(mem, &c, title) {
                return Some(c);
            }
            v += 4;
        }
        sub[j] = orig;
    }
    None
}

fn reads_title(mem: &ProcMem, p: &PointerPath, title: &str) -> bool {
    p.resolve_addr(mem)
        .and_then(|a| mem.read_cstring(a, 80))
        .map(|s| s.contains(title))
        .unwrap_or(false)
}

/// Verify each discovered chain reads a sane live value. Returns the count OK.
fn verify(mem: &ProcMem, f: &FoundOffsets, bpm_expect: &[f32; 4]) -> usize {
    let mut ok = 0;
    if let Some(m) = &f.master {
        match m.resolve_addr(mem).and_then(|a| mem.read::<u8>(a)) {
            Some(v) if v < 4 => {
                ok += 1;
                println!("  [master] {} = {v}", m.to_line());
            }
            other => println!("  [master] {} = {other:?}  ⚠", m.to_line()),
        }
    } else {
        println!("  [master] (not found)");
    }
    for d in 0..4 {
        ok += vfield(mem, &format!("d{} bpm  ", d + 1), &f.bpm[d], |a| {
            // Plausible tempo (deck may be pitched); exact match not required.
            let _ = bpm_expect;
            mem.read::<f32>(a).filter(|v| *v >= 40.0 && *v <= 320.0).map(|v| format!("{v}"))
        });
        ok += vfield(mem, &format!("d{} pos  ", d + 1), &f.pos[d], |a| {
            mem.read::<i64>(a).filter(|v| *v > 0).map(|v| format!("{v} samples"))
        });
        ok += vfield(mem, &format!("d{} track", d + 1), &f.track[d], |a| {
            mem.read_cstring(a, 80).filter(|s| s.contains("Title"))
        });
        ok += vfield(mem, &format!("d{} anlz ", d + 1), &f.anlz[d], |a| {
            mem.read_cstring(a, 200).filter(|s| s.contains(".DAT"))
        });
    }
    ok
}

fn vfield(
    mem: &ProcMem,
    label: &str,
    p: &Option<PointerPath>,
    read: impl Fn(usize) -> Option<String>,
) -> usize {
    match p {
        None => {
            println!("  [{label}] (not found)");
            0
        }
        Some(p) => match p.resolve_addr(mem).and_then(read) {
            Some(s) => {
                println!("  [{label}] {}  = {s}", p.to_line());
                1
            }
            None => {
                println!("  [{label}] {}  ⚠ bad value", p.to_line());
                0
            }
        },
    }
}

