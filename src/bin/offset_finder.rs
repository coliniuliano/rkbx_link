// Automated Rekordbox offset finder — a single guided wizard.
//
// It discovers every pointer chain rkbx_link needs, FULLY BLIND: it knows no
// prior offsets and assumes nothing that carries between versions or platforms.
// It only reads memory, searches for values you can see on screen, traces
// pointer chains from raw memory, and cross-validates them by having you change
// Rekordbox state (nudge pitch, seek, reload, switch master) — keeping only the
// chains that behave correctly. The single OS-specific piece is the memory
// reader (src/finder/procmem.rs); everything else is portable.
//
//   cargo run --release --bin offset_finder
//
// Requires Rekordbox running and re-signed (./resign_rekordbox.sh).

#[path = "../finder/procmem.rs"]
mod procmem;
#[path = "../finder/scan.rs"]
mod scan;

use std::io::{self, Write};

use procmem::ProcMem;
use scan::{PointerPath, ScanOpts, Scanner};

const PROCESS: &str = "rekordbox";
const OFFSETS_FILE: &str = "data/offsets-macos";
const SAMPLE_RATE: i64 = 44100;

/// Calibration tracks: (title/filename, exact BPM). Generated by
/// tools/generate_calibration.py with integer samples-per-beat so Rekordbox
/// analyses them to these exact BPMs — the wizard uses them without asking.
/// Load track d on deck d.
const CAL: [(&str, f32); 4] = [
    ("RKBXCAL_ONE_100", 100.0),
    ("RKBXCAL_TWO_125", 125.0),
    ("RKBXCAL_THREE_150", 150.0),
    ("RKBXCAL_FOUR_175", 175.0),
];

fn main() {
    let args: Vec<String> = std::env::args().collect();
    println!("=== Rekordbox Automated Offset Finder ===\n");
    let mem = match ProcMem::attach(PROCESS) {
        Ok(m) => m,
        Err(e) => {
            eprintln!("✗ {e}");
            std::process::exit(1);
        }
    };
    println!(
        "✓ Attached to {PROCESS} (pid {}, base 0x{:X}, image {} MiB)\n",
        mem.pid,
        mem.base,
        mem.image_size / (1024 * 1024)
    );

    // Hidden helpers.
    if args.get(1).map(|s| s == "check").unwrap_or(false) {
        cmd_check(&mem, &args);
        return;
    }
    if args.get(1).map(|s| s == "master").unwrap_or(false) {
        println!("Building pointer map...");
        let mut scanner = Scanner::new(&mem);
        scanner.build_pointer_map();
        match discover_master(&scanner, &mem) {
            Some(p) => {
                let v = p.resolve_addr(&mem).and_then(|a| mem.read::<u8>(a));
                println!("\n✓ master: {}  = {v:?}", p.to_line());
            }
            None => println!("\n⚠ master: not found"),
        }
        return;
    }
    // `master-verify <deck 1..4>`: after a RESTART, keep only the saved master
    // candidates that STILL read the given master deck's index. Only a truly
    // restart-stable chain reconstructs correctly on the fresh process. This is
    // the definitive validation (a restart is what aliases can't survive).
    if args.get(1).map(|s| s == "master-verify").unwrap_or(false) {
        let want = args.get(2).and_then(|s| s.parse::<u8>().ok()).map(|d| d - 1);
        let Some(want) = want else {
            eprintln!("usage: master-verify <deck 1..4>  (the deck currently set as master)");
            return;
        };
        let saved = std::fs::read_to_string(master_cand_file()).unwrap_or_default();
        let survivors: Vec<PointerPath> = saved
            .lines()
            .filter_map(parse_pointer_line)
            .filter(|c| c.resolve_addr(&mem).and_then(|a| mem.read::<u8>(a)) == Some(want))
            .collect();
        println!(
            "{} of the saved candidates still read master index {} after restart:",
            survivors.len(),
            want + 1
        );
        for c in &survivors {
            println!("  {}", c.to_line());
        }
        match survivors.iter().min_by_key(|c| (c.depth(), c.rest.iter().sum::<usize>())) {
            Some(best) => println!("\n✓ restart-stable master: {}", best.to_line()),
            None => println!("\n⚠ none survived — re-run the wizard's master step."),
        }
        return;
    }
    // `canon <b1> <b2> <b3> <b4> [p1s p2s p3s p4s]`: run the real Step-2
    // discovery with the given deck BPMs (and optional seek positions in
    // seconds). Prints the canonical chains. For live testing without the cal
    // tracks loaded.
    if args.get(1).map(|s| s == "canon").unwrap_or(false) {
        println!("Building pointer map...");
        let mut scanner = Scanner::new(&mem);
        scanner.build_pointer_map();
        let nums: Vec<f32> = args[2..].iter().filter_map(|s| s.parse().ok()).collect();
        let bpms: [f32; 4] = std::array::from_fn(|i| nums.get(i).copied().unwrap_or(0.0));
        let expected: [i64; 4] =
            std::array::from_fn(|i| (nums.get(4 + i).copied().unwrap_or(0.0) as i64) * SAMPLE_RATE);
        let (pos, bpm) = discover_decks_pos_bpm(&scanner, &mem, expected, bpms);
        for d in 0..4 {
            println!(
                "deck {}: bpm [{}]  pos [{}]",
                d + 1,
                bpm[d].as_ref().map(|p| p.to_line()).unwrap_or_else(|| "-".into()),
                pos[d].as_ref().map(|p| p.to_line()).unwrap_or_else(|| "-".into()),
            );
        }
        // Track test via JOINT scan: read each deck's title buffer (known chain),
        // then joint2_path across each pair of decks. The pair sharing the exact
        // path (3&4) yields the shared subchain fast.
        println!("\ntrack (joint2 across deck pairs):");
        let kv = [
            vec![0x0usize, 0x270, 0x38, 0x80, 0x28, 0xF0, 0x4],
            vec![0x8, 0x270, 0x38, 0x68, 0x28, 0xF0, 0x4],
            vec![0x10, 0x270, 0x38, 0x48, 0x28, 0xF0, 0x4],
            vec![0x18, 0x270, 0x38, 0x48, 0x28, 0xF0, 0x4],
        ];
        let mut ds = [0usize; 4];
        let mut ta = [0usize; 4];
        for d in 0..4 {
            ds[d] = bpm[d].as_ref().and_then(|c| deck_struct_addr(&mem, c)).unwrap_or(0);
            ta[d] = (PointerPath { rva: 0x4D8AA18, rest: kv[d].clone() }).resolve_addr(&mem).unwrap_or(0);
        }
        // real titles via known chains
        let titles: Vec<String> = (0..4)
            .map(|d| {
                (PointerPath { rva: 0x4D8AA18, rest: kv[d].clone() })
                    .resolve_addr(&mem)
                    .and_then(|a| mem.read_cstring(a, 60))
                    .and_then(|s| s.split("Title: ").nth(1).map(|x| x.lines().next().unwrap_or("").to_string()))
                    .unwrap_or_default()
            })
            .collect();
        let mut shared: Option<Vec<usize>> = None;
        for (a, b) in [(2, 3), (0, 1), (0, 2)] {
            let t = std::time::Instant::now();
            let p = scanner.joint2_path(ds[a], ta[a], ds[b], ta[b], 0x800, 0x300, 7);
            println!(
                "  joint {}&{}: {:.1}s → {}",
                a + 1, b + 1, t.elapsed().as_secs_f32(),
                p.as_ref().map(|v| v.iter().map(|o| format!("{o:X}")).collect::<Vec<_>>().join(" ")).unwrap_or_else(|| "NONE".into())
            );
            if let Some(pp) = p {
                if shared.as_ref().map(|s| pp.len() < s.len()).unwrap_or(true) { shared = Some(pp); }
                if shared.as_ref().map(|s| s.len() <= 6).unwrap_or(false) { break; }
            }
        }
        if let Some(sh) = &shared {
            for d in 0..4 {
                let c = track_chain_for_deck(&mem, 0x4D8AA18, kv[d][0], &titles[d], sh);
                let known = PointerPath { rva: 0x4D8AA18, rest: kv[d].clone() };
                println!(
                    "  deck {} '{}': found [{}]  known [{}]  match={}",
                    d + 1, titles[d],
                    c.as_ref().map(|p| p.to_line()).unwrap_or_else(|| "NONE".into()),
                    known.to_line(),
                    c.as_ref() == Some(&known),
                );
            }
        }
        return;
    }
    run_wizard(&mem);
}

