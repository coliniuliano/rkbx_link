fn run_wizard(mem: &ProcMem) {
    banner();

    // --- Step 1: load calibration tracks -----------------------------------
    section("Step 1 — load the calibration tracks");
    println!("If you haven't already, generate them:  python3 tools/generate_calibration.py");
    println!("Then in Rekordbox load one on each deck:");
    for (d, (name, bpm)) in CAL.iter().enumerate() {
        println!("    deck {} → {name}.wav  ({bpm} BPM)", d + 1);
    }
    println!("Set every deck's tempo/pitch fader to 0% and wait for BPMs to show.");
    pause("Press Enter when all 4 decks are loaded and analysed");

    println!("\nScanning memory (a few seconds)...");
    let mut scanner = Scanner::new(mem);
    scanner.build_pointer_map();
    println!("✓ ready.\n");

    let mut found = FoundOffsets::default();

    // --- Step 2: playhead + tempo, found TOGETHER in the deck object -------
    // sample_position is the robust anchor: a big i64 that tracks the playhead
    // exactly. current_bpm drifts (it's the local grid tempo at the playhead),
    // so we anchor on position and take bpm as the sibling in the same struct.
    // Each validates the other: the real deck object holds BOTH.
    section("Step 2 — playhead + tempo (in the deck object)");
    println!("Seek each deck to a DIFFERENT spot and PAUSE (so positions are distinct):");
    println!("   deck 1 → ~0:30    deck 2 → ~1:00    deck 3 → ~1:30    deck 4 → ~2:00");
    println!("(Keep pitch at 0%. I already know the calibration BPMs, so no need to type them.)");
    pause("Press Enter with each deck paused at its spot");
    let obpm: [f32; 4] = [CAL[0].1, CAL[1].1, CAL[2].1, CAL[3].1];
    let expected: [i64; 4] = [30 * SAMPLE_RATE, 60 * SAMPLE_RATE, 90 * SAMPLE_RATE, 120 * SAMPLE_RATE];
    let (pos4, bpm4) = discover_decks_pos_bpm(&scanner, mem, expected, obpm);
    for d in 0..4 {
        found.pos[d] = pos4[d].clone();
        found.bpm[d] = bpm4[d].clone();
        report(&format!("deck {} pos", d + 1), &found.pos[d]);
        report(&format!("deck {} bpm", d + 1), &found.bpm[d]);
    }

    // --- Step 3: track_info — deck-relative subchain via JOINT scan ---------
    // The title lives on the heap ("Title: <song>" is unique). Its chain hangs
    // off the deck struct we already found for pos/bpm, but many coincidental
    // paths reach the buffer. The real one is the SUBCHAIN two decks SHARE: a
    // joint scan (each backward step must advance both decks by the same offset)
    // prunes coincidences and returns that shared subchain fast. We then apply
    // it to every deck, substituting the single per-deck offset where it differs.
    section("Step 3 — track info");
    let img_end = mem.base + mem.image_size;
    let mut ds = [0usize; 4];
    let mut ta = [0usize; 4];
    let (mut base_rva, mut didx) = (0usize, [0usize; 4]);
    for d in 0..4 {
        if let Some(b) = &found.bpm[d] {
            base_rva = b.rva;
            didx[d] = b.rest[0];
            ds[d] = deck_struct_addr(mem, b).unwrap_or(0);
        }
        ta[d] = scanner
            .find_string(&format!("Title: {}", CAL[d].0))
            .into_iter()
            .find(|a| *a < mem.base || *a >= img_end) // heap only
            .unwrap_or(0);
    }
    // Shared subchain via joint scan over deck pairs; keep the shortest.
    let mut shared: Option<Vec<usize>> = None;
    for (a, b) in [(2, 3), (0, 1), (0, 2), (1, 3), (0, 3), (1, 2)] {
        if [ds[a], ds[b], ta[a], ta[b]].contains(&0) {
            continue;
        }
        if let Some(p) = scanner.joint2_path(ds[a], ta[a], ds[b], ta[b], 0x800, 0x300, 7) {
            if shared.as_ref().map(|s| p.len() < s.len()).unwrap_or(true) {
                shared = Some(p);
            }
            if shared.as_ref().map(|s| s.len() <= 6).unwrap_or(false) {
                break; // canonical-length shared subchain found
            }
        }
    }
    match &shared {
        Some(sh) => {
            println!("  shared subchain: {}", sh.iter().map(|o| format!("{o:X}")).collect::<Vec<_>>().join(" "));
            for d in 0..4 {
                found.track[d] = track_chain_for_deck(mem, base_rva, didx[d], CAL[d].0, sh);
                report(&format!("deck {} track", d + 1), &found.track[d]);
            }
        }
        None => println!("  ⚠ no shared track subchain found"),
    }

    // --- Step 5: anlz_path (re-analyse in order, map newest .DATs to decks) -
    section("Step 4 — ANLZ (beatgrid file) path");
    println!("Re-analyse all four tracks IN ORDER deck 1 → 2 → 3 → 4");
    println!("(right-click each deck's track → Analyze). This lets me match each");
    println!("freshly-written .DAT file to its deck by modification time.");
    pause("Press Enter after analysing all four, in order");
    let dats = newest_dats_in_deck_order(4);
    if dats.len() == 4 {
        let mut anlz_cands: [Vec<PointerPath>; 4] = std::array::from_fn(|_| Vec::new());
        let opts = ScanOpts { max_depth: 5, ..ScanOpts::default() };
        for d in 0..4 {
            let mut cs: Vec<PointerPath> = Vec::new();
            for a in scanner.find_string(&dats[d]).iter().take(10) {
                for c in scanner.reverse_scan(*a, opts) {
                    if c.resolve_addr(mem)
                        .and_then(|x| mem.read_cstring(x, 260))
                        .map(|s| s.contains(&dats[d]))
                        .unwrap_or(false)
                    {
                        cs.push(c);
                    }
                }
            }
            cs.sort_by_key(|p| (p.depth(), p.rest.iter().sum::<usize>(), p.rva));
            cs.dedup();
            anlz_cands[d] = cs;
        }
        let picked = enforce_shared_base(&anlz_cands);
        for d in 0..4 {
            found.anlz[d] = picked[d].clone();
            report(&format!("deck {} anlz", d + 1), &found.anlz[d]);
        }
    } else {
        println!("⚠ Expected 4 recent .DAT files, found {}. Skipping ANLZ.", dats.len());
    }

    // --- Step 5: masterdeck_index (byte that tracks the master deck) --------
    section("Step 5 — master deck index");
    found.master = discover_master(&scanner, mem);
    report("master index", &found.master);

    // --- Verify + emit -----------------------------------------------------
    section("Verification (live values)");
    let n = verify(mem, &found, &obpm);
    println!("\n{n}/17 chains discovered and reading sane values.");

    section("Result");
    let version = detect_version().unwrap_or_else(|| "UNKNOWN".to_string());
    let block = found.to_block(&version);
    println!("{block}");

    print!("Append this block to {OFFSETS_FILE}? (y/n): ");
    io::stdout().flush().ok();
    if read_line().trim().eq_ignore_ascii_case("y") {
        match append_block(OFFSETS_FILE, &block) {
            Ok(()) => println!(
                "✓ Written. Set `keeper.rekordbox_version {version}` in config and run rkbx_link."
            ),
            Err(e) => println!("✗ Failed to write: {e}"),
        }
    } else {
        println!("Not written.");
    }
}

